import SwiftUI
import Domain
import Application

/// Home v1: header, plan card, week strip, selected day, up next and Recovery. Every value
/// comes from the view model's `HomeOverview`; this file only lays it out.
struct HomeView: View {
    let viewModel: HomeViewModel
    let onOpenSession: (String) -> Void

    @Environment(\.accessibilityReduceMotion) private var reduceMotion
    #if DEBUG
    @State private var modelLab: ModelLabViewModel?
    #endif

    var body: some View {
        ScrollView {
            if let overview = viewModel.overview {
                VStack(alignment: .leading, spacing: Theme.Spacing.homeBlocks) {
                    header(overview.header)
                    VStack(alignment: .leading, spacing: Theme.Spacing.compact) {
                        PlanCardView(card: overview.planCard)
                            #if DEBUG
                            .contextMenu {
                                Text("Generated by \(viewModel.generatedBy ?? "unknown")")
                            }
                            #endif
                        if let locked = overview.lockedLine {
                            Text(locked)
                                .font(Theme.Typography.lockedLine)
                                .foregroundStyle(Theme.Palette.mutedText)
                                .fixedSize(horizontal: false, vertical: true)
                                .accessibilityIdentifier("home.locked")
                        }
                    }
                    if let feedback = viewModel.feedback {
                        SuggestionCardView(store: feedback)
                    }
                    if let week = overview.week {
                        weekBlock(week)
                    }
                    if overview.selectedCard != nil || overview.upNext != nil {
                        VStack(spacing: Theme.Spacing.selectedToUpNext) {
                            if let card = overview.selectedCard {
                                DayCardView(card: card, hasStrength: overview.strengthCard != nil, onOpenSession: onOpenSession)
                            }
                            if let strength = overview.strengthCard {
                                StrengthRowView(card: strength, onOpen: onOpenSession)
                            }
                            if let upNext = overview.upNext {
                                UpNextCard(upNext: upNext) { onOpenSession(upNext.sessionID) }
                            }
                            if let latest = viewModel.latestNote {
                                LatestCoachNoteCardView(card: latest) { onOpenSession(latest.sessionId) }
                            }
                        }
                    } else if let latest = viewModel.latestNote {
                        LatestCoachNoteCardView(card: latest) { onOpenSession(latest.sessionId) }
                    }
                    RecoverySection(recovery: overview.recovery) {
                        Task { await viewModel.retryRecovery() }
                    }
                }
                .padding(.horizontal, Theme.Spacing.homeSide)
                .padding(.top, Theme.Spacing.homeTop)
                .padding(.bottom, Theme.Spacing.tabBarClearance)
            }
        }
        .refreshable { await viewModel.refresh() }
        .background(Theme.Palette.background.ignoresSafeArea())
        .task { await viewModel.load() }
        #if DEBUG
        .fullScreenCover(item: $modelLab) { lab in
            ModelLabView(viewModel: lab) { modelLab = nil }
        }
        #endif
    }

    // MARK: Header

    private func header(_ header: HomeOverview.Header) -> some View {
        HStack(spacing: Theme.Spacing.headerGap) {
            headerContent(header)
            #if DEBUG
            Menu { debugMenu } label: {
                Image(systemName: "ladybug")
                    .font(Theme.Typography.headerAvatarGlyph)
                    .foregroundStyle(Theme.Palette.mutedText)
                    .frame(width: Theme.Size.minTouchTarget, height: Theme.Size.minTouchTarget)
                    .contentShape(Rectangle())
            }
            .accessibilityLabel("Debug menu")
            .accessibilityIdentifier("home.debugMenu")
            #endif
        }
    }

    private func headerContent(_ header: HomeOverview.Header) -> some View {
        HStack(spacing: Theme.Spacing.headerGap) {
            // A neutral icon: there is no user name to take an initial from.
            Image(systemName: "waveform.path.ecg")
                .font(Theme.Typography.headerAvatarGlyph)
                .foregroundStyle(Theme.Palette.accent)
                .frame(width: Theme.Size.headerAvatar, height: Theme.Size.headerAvatar)
                .background(Theme.Palette.thumbnail, in: Circle())
                .overlay { Circle().strokeBorder(Theme.Palette.iconRing, lineWidth: Theme.Size.borderWidth) }
                .accessibilityHidden(true)
            VStack(alignment: .leading, spacing: Theme.Spacing.tight / 2) {
                Text(header.dateCaption)
                    .font(Theme.Typography.homeDate)
                    .foregroundStyle(Theme.Palette.mutedText)
                Text(header.greeting)
                    .font(Theme.Typography.greeting)
                    .foregroundStyle(Theme.Palette.text)
                    .accessibilityAddTraits(.isHeader)
            }
            Spacer(minLength: 0)
        }
        .contentShape(Rectangle())
        .accessibilityElement(children: .combine)
        .accessibilityIdentifier("home.header")
        #if DEBUG
        .contextMenu { debugMenu }
        #endif
    }

    #if DEBUG
    /// The header's ladybug button, or a long-press on the header. Compiled out of release builds.
    @ViewBuilder
    private var debugMenu: some View {
        if let json = viewModel.planJSON {
            Button("Copy plan JSON", systemImage: "doc.on.doc") { Clipboard.copy(json) }
        }
        if let json = viewModel.sleepJSON {
            Button("Copy sleep JSON", systemImage: "moon") { Clipboard.copy(json) }
        }
        if let json = viewModel.recoveryJSON {
            Button("Copy recovery JSON", systemImage: "waveform.path.ecg") { Clipboard.copy(json) }
        }
        Button("Copy coach note facts", systemImage: "list.bullet.rectangle") {
            Task { if let facts = await viewModel.coachNoteFacts() { Clipboard.copy(facts) } }
        }
        if let makeLab = viewModel.makeModelLab {
            Button("Model Lab", systemImage: "cpu") { modelLab = makeLab() }
        }
        Button("Reset plan", systemImage: "trash", role: .destructive) {
            Task { await viewModel.reset() }
        }
    }
    #endif

    // MARK: Week

    private func weekBlock(_ week: HomeOverview.Week) -> some View {
        VStack(alignment: .leading, spacing: Theme.Spacing.weekTitleToStrip) {
            HStack(spacing: 0) {
                Text("Your week")
                    .font(Theme.Typography.weekTitle)
                    .foregroundStyle(Theme.Palette.text)
                    .accessibilityAddTraits(.isHeader)
                Spacer(minLength: Theme.Spacing.compact)
                Text(week.rangeLabel)
                    .font(Theme.Typography.weekRange)
                    .foregroundStyle(Theme.Palette.mutedText)
                    .accessibilityIdentifier("home.weekRange")
                chevron("chevron.left", label: "Previous week", identifier: "weekPrev", enabled: week.canGoBack) {
                    change { viewModel.showPreviousWeek() }
                }
                chevron("chevron.right", label: "Next week", identifier: "weekNext", enabled: week.canGoForward) {
                    change { viewModel.showNextWeek() }
                }
            }
            HStack(spacing: Theme.Spacing.dayPills) {
                ForEach(week.days) { day in
                    DayPill(day: day) { change { viewModel.select(day.date) } }
                }
            }
        }
    }

    private func chevron(_ symbol: String, label: String, identifier: String, enabled: Bool, action: @escaping () -> Void) -> some View {
        Button(action: action) {
            Image(systemName: symbol)
                .font(Theme.Typography.cardIconGlyph)
                .foregroundStyle(Theme.Palette.text.opacity(enabled ? 1 : Theme.Opacity.disabledChevron))
                .frame(width: Theme.Size.minTouchTarget, height: Theme.Size.minTouchTarget)
                .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .disabled(!enabled)
        .accessibilityLabel(label)
        .accessibilityIdentifier(identifier)
    }

    private func change(_ update: () -> Void) {
        if reduceMotion {
            update()
        } else {
            withAnimation(.easeOut(duration: Theme.Motion.selection)) { update() }
        }
    }
}

// MARK: - Plan card

private struct PlanCardView: View {
    let card: HomeOverview.PlanCard

    var body: some View {
        ViewThatFits(in: .horizontal) {
            HStack(spacing: Theme.Spacing.planCardGap) { ring; details }
            VStack(alignment: .leading, spacing: Theme.Spacing.planCardGap) { ring; details }
        }
        .frame(maxWidth: .infinity, alignment: .leading)
        .padding(Theme.Spacing.planCardPadding)
        .background(Theme.Palette.card, in: RoundedRectangle(cornerRadius: Theme.Radius.largeCard, style: .continuous))
        .overlay {
            RoundedRectangle(cornerRadius: Theme.Radius.largeCard, style: .continuous)
                .strokeBorder(Theme.Palette.cardBorder, lineWidth: Theme.Size.borderWidth)
        }
    }

    private var ring: some View {
        ZStack {
            Circle()
                .stroke(Theme.Palette.ringTrack, lineWidth: Theme.Size.ringStroke)
            Circle()
                .trim(from: 0, to: card.adherence ?? 0)
                .stroke(Theme.Palette.accent, style: StrokeStyle(lineWidth: Theme.Size.ringStroke, lineCap: .round))
                .rotationEffect(.degrees(-90))
            VStack(spacing: 0) {
                Text(card.ringValue)
                    .font(Theme.Typography.ringValue)
                    .foregroundStyle(Theme.Palette.text)
                Text(card.ringCaption)
                    .font(Theme.Typography.ringCaption)
                    .foregroundStyle(Theme.Palette.mutedText)
                    .multilineTextAlignment(.center)
            }
            .minimumScaleFactor(0.6)
            .padding(Theme.Size.ringStroke * 1.5)
        }
        .frame(width: Theme.Size.ring, height: Theme.Size.ring)
        .accessibilityElement(children: .ignore)
        .accessibilityLabel(card.ringAccessibilityLabel)
        .accessibilityIdentifier("home.ring")
    }

    private var details: some View {
        VStack(alignment: .leading, spacing: Theme.Spacing.tight) {
            Text(card.raceTitle)
                .font(Theme.Typography.raceTitle)
                .foregroundStyle(Theme.Palette.mutedText)
                .accessibilityIdentifier("home.raceTitle")
            countdown
            if let pill = card.pill {
                Text(pill.text)
                    .font(Theme.Typography.phasePill)
                    .tracking(Theme.Typography.phasePillTracking)
                    .textCase(.uppercase)
                    .foregroundStyle(pill.isMuted ? Theme.Palette.mutedText : Theme.Palette.accent)
                    .padding(.vertical, Theme.Spacing.phasePillVertical)
                    .padding(.horizontal, Theme.Spacing.phasePillHorizontal)
                    .background(
                        pill.isMuted ? Theme.Palette.innerCard : Theme.Palette.accentSoft,
                        in: RoundedRectangle(cornerRadius: Theme.Radius.phasePill, style: .continuous)
                    )
                    .padding(.top, Theme.Spacing.tight)
                    // Drawn uppercase; read as written, so VoiceOver and tests always get the same words.
                    .accessibilityLabel(pill.text)
                    .accessibilityIdentifier("home.phase")
            }
            if let caption = card.weekCaption {
                Text(caption)
                    .font(Theme.Typography.weekCaption)
                    .foregroundStyle(Theme.Palette.mutedText)
                    .padding(.top, Theme.Spacing.pillToCaption - Theme.Spacing.tight)
                    .accessibilityIdentifier("home.weekCaption")
            }
        }
    }

    private var countdown: some View {
        HStack(alignment: .firstTextBaseline, spacing: Theme.Spacing.compact) {
            Text(card.countdownValue)
                .font(card.countdownUnit == nil ? Theme.Typography.countdownWords : Theme.Typography.countdown)
                .foregroundStyle(Theme.Palette.text)
                .lineLimit(1)
                .minimumScaleFactor(0.6)
            if let unit = card.countdownUnit {
                Text(unit)
                    .font(Theme.Typography.countdownUnit)
                    .foregroundStyle(Theme.Palette.mutedText)
            }
        }
        .accessibilityElement(children: .ignore)
        .accessibilityLabel(card.countdownAccessibilityLabel)
        .accessibilityIdentifier("home.countdown")
    }
}

// MARK: - Week strip

private struct DayPill: View {
    let day: HomeOverview.Day
    let onTap: () -> Void

    var body: some View {
        Button(action: onTap) {
            VStack(spacing: Theme.Spacing.dayPillLines) {
                Text(day.weekdayShort)
                    .font(Theme.Typography.dayWeekday)
                    .foregroundStyle(day.isSelected ? Theme.Palette.onAccent : Theme.Palette.text)
                Text(day.dayNumber)
                    .font(Theme.Typography.dayNumber)
                    .foregroundStyle(numberColor)
                icon
                    .frame(width: Theme.Size.dayIcon, height: Theme.Size.dayIcon)
            }
            .lineLimit(1)
            .minimumScaleFactor(0.5)
            .frame(maxWidth: .infinity, minHeight: Theme.Size.minTouchTarget)
            .padding(.vertical, Theme.Spacing.dayPillVertical)
            .background(
                day.isSelected ? Theme.Palette.accent : Theme.Palette.innerCard,
                in: RoundedRectangle(cornerRadius: Theme.Radius.dayPill, style: .continuous)
            )
            .overlay {
                RoundedRectangle(cornerRadius: Theme.Radius.dayPill, style: .continuous)
                    .strokeBorder(day.isSelected ? Theme.Palette.accent : Theme.Palette.cardBorder, lineWidth: Theme.Size.borderWidth)
            }
            .contentShape(RoundedRectangle(cornerRadius: Theme.Radius.dayPill, style: .continuous))
        }
        .buttonStyle(.plain)
        .accessibilityLabel(day.accessibilityLabel)
        .accessibilityAddTraits(day.isSelected ? .isSelected : [])
        .accessibilityIdentifier("home.day.\(day.id)")
    }

    private var numberColor: Color {
        if day.isSelected { return Theme.Palette.onAccent }
        return day.isToday ? Theme.Palette.accent : Theme.Palette.text
    }

    @ViewBuilder
    private var icon: some View {
        if day.isRaceDay {
            Image(systemName: "flag.fill")
                .font(Theme.Typography.dayGlyph)
                .foregroundStyle(day.isSelected ? Theme.Palette.onAccent : Theme.Palette.accent)
        } else if let type = day.sessionType, let status = day.status {
            let look = SessionStatusPresentation.presentation(status)
            // The selected pill is accent-filled: a dark icon, and a dark badge with an accent check.
            SessionTypeIcon(type: type, size: Theme.Size.dayIcon, color: day.isSelected ? Theme.Palette.onAccent : look.iconColor, isStruck: look.iconDecoration == .strike)
                .overlay(alignment: .topTrailing) {
                    if look.showsCheckBadge {
                        CheckBadge(
                            size: Theme.Size.checkBadgeSmall,
                            fill: day.isSelected ? Theme.Palette.onAccent : Theme.Palette.completed,
                            check: day.isSelected ? Theme.Palette.accent : Theme.Palette.onAccent
                        )
                        .offset(x: Theme.Size.checkBadgeOffset.width, y: Theme.Size.checkBadgeOffset.height)
                    }
                }
                .overlay(alignment: .bottomTrailing) {
                    if let strength = day.strengthStatus {
                        StrengthBadge(status: strength, color: day.isSelected ? Theme.Palette.onAccent : nil)
                            .offset(x: Theme.Size.checkBadgeOffset.width, y: -Theme.Size.checkBadgeOffset.height)
                    }
                }
        } else if let strength = day.strengthStatus {
            let look = SessionStatusPresentation.presentation(strength)
            StrengthIcon(size: Theme.Size.dayIcon, color: day.isSelected ? Theme.Palette.onAccent : look.iconColor, isStruck: look.iconDecoration == .strike)
        } else {
            Color.clear
        }
    }
}

// MARK: - Up next

private struct UpNextCard: View {
    let upNext: HomeOverview.UpNext
    let onOpen: () -> Void

    /// The whole card opens the session detail.
    var body: some View {
        Button(action: onOpen) {
            HStack(spacing: Theme.Spacing.selectedCardGap) {
                SessionTypeIcon(type: upNext.type, size: Theme.Size.upNextIcon, color: Theme.Palette.text)
                    .frame(width: Theme.Size.upNextThumbnail, height: Theme.Size.upNextThumbnail)
                    .background(Theme.Palette.thumbnail, in: RoundedRectangle(cornerRadius: Theme.Radius.thumbnail, style: .continuous))
                    .overlay {
                        RoundedRectangle(cornerRadius: Theme.Radius.thumbnail, style: .continuous)
                            .strokeBorder(Theme.Palette.iconRing, lineWidth: Theme.Size.borderWidth)
                    }
                VStack(alignment: .leading, spacing: Theme.Spacing.tight / 2) {
                    Text(upNext.caption)
                        .font(Theme.Typography.upNextCaption)
                        .foregroundStyle(Theme.Palette.mutedText)
                    Text(upNext.name)
                        .font(Theme.Typography.upNextName)
                        .foregroundStyle(Theme.Palette.text)
                    Text(upNext.meta)
                        .font(Theme.Typography.upNextMeta)
                        .foregroundStyle(Theme.Palette.mutedText)
                }
                .multilineTextAlignment(.leading)
                Spacer(minLength: 0)
                Image(systemName: "chevron.right")
                    .font(Theme.Typography.arrowGlyph)
                    .foregroundStyle(Theme.Palette.mutedText)
                    .accessibilityHidden(true)
            }
            .padding(.vertical, Theme.Spacing.upNextVertical)
            .padding(.horizontal, Theme.Spacing.upNextHorizontal)
            .background(Theme.Palette.innerCard, in: RoundedRectangle(cornerRadius: Theme.Radius.upNext, style: .continuous))
            .overlay {
                RoundedRectangle(cornerRadius: Theme.Radius.upNext, style: .continuous)
                    .strokeBorder(Theme.Palette.cardBorder, lineWidth: Theme.Size.borderWidth)
            }
            .contentShape(RoundedRectangle(cornerRadius: Theme.Radius.upNext, style: .continuous))
        }
        .buttonStyle(.plain)
        .accessibilityElement(children: .combine)
        .accessibilityHint("Opens the session")
        .accessibilityIdentifier("upNextCard")
    }
}

